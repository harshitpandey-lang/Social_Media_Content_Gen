from google import genai
from PIL import Image
import os
import json
from dotenv import load_dotenv
load_dotenv()
gemini=genai.Client(api_key=os.getenv("GEMINI_API_KEY"))

def Vision_Agent(Img):
    response=gemini.models.generate_content(model="models/gemini-2.5-flash",
    contents=["You are a brilliant image describer. Describe this image, no extra explanation, covering all the necesaary and relevant details",Img])
    return response.text

def Strategy_Agent(platform ):
    platform_desc={"linkedin":{"Tone":"Professional",
                           "Emojis":"Very minimal",
                           "Hashtags":True},
               "instagram":{"Tone":"Casual",
                            "Emojis":"Moderate",
                            "Hashtags":True},
               "facebook":{"Tone":"Casual" ,
                           "Emojis":"Moderate",
                           "Hashtags":True},
               "twitter":{"Tone":"Professional",
                          "Emojis":"Minimal",
                          "Hashtags":True}}
    return platform_desc[platform.lower()]

def Caption_Agent(img_desc,platf_desc):
    
    strategy_json = json.dumps(platf_desc, indent=2)
    prompt=f"""
    You are a brilliant Social media caption generator that works on generating caption for the the posts of the users according to the platfrom requirements.
    
    You will be provided with an image description and platform characteristics according to which a caption will be generated by you.
    Output ONLY the final caption text.
    Do NOT include explanations, breakdowns, suggestions, alternatives, headings, markdown, or commentary.
    It should like a caption according to the required platform is generated. Work your best on that.
    Return exactly one caption and nothing else.
    
    Image Description:{img_desc}
    Platform Description:{strategy_json}
    
    Thank you for your efforts! 
    """
    response=gemini.models.generate_content(model="models/gemini-2.5-flash",
    contents=[prompt])
    return response.text

